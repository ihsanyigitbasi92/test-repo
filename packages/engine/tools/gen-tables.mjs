#!/usr/bin/env node
/**
 * Generates the integer lookup tables the engine uses instead of transcendental math (D-098).
 * This script is the ONLY place where Math.exp/pow/log/tanh may appear; the engine runtime never calls them.
 * Run: node packages/engine/tools/gen-tables.mjs   (writes packages/engine/src/tables/*.ts)
 * Sources: 02 §2.4.1 (Gompertz hazard), 03 §2.3.2 (log-normal gap σ=0.45), 02 §2.2.2 (tanh joy target),
 *          02 §2.1.4 / §2.3.4 (exponential decays by gap).
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'tables');
mkdirSync(out, { recursive: true });
const header = (what) => `/* GENERATED by tools/gen-tables.mjs — do not edit. ${what} */\n`;

// 1) Hazard: yearly death probability in ppm for age 18..100 × health bucket 0..20 (h = bucket × 5).
const A = 0.0003, B = Math.log(2) / 8, K = 1.0;
const hazard = [];
for (let age = 18; age <= 100; age++) {
  const row = [];
  for (let b = 0; b <= 20; b++) {
    const h = b * 5;
    const p = age >= 100 ? 1 : A * Math.exp(B * (age - 18)) * Math.exp(K * (50 - h) / 50);
    row.push(Math.min(1_000_000, Math.round(p * 1_000_000)));
  }
  hazard.push(row);
}
writeFileSync(join(out, 'hazard.ts'), header('Gompertz hazard, ppm, [age-18][health/5]') +
  `export const HAZARD_MIN_AGE = 18;\nexport const HAZARD_PPM: readonly (readonly number[])[] = ${JSON.stringify(hazard)};\n`);

// 2) Log-normal gap multiplier quantiles: 256 entries of exp(0.45·z) in per-mille (Acklam inverse normal).
function invNorm(p) {
  const a = [-3.969683028665376e1, 2.209460984245205e2, -2.759285104469687e2, 1.38357751867269e2, -3.066479806614716e1, 2.506628277459239];
  const b = [-5.447609879822406e1, 1.615858368580409e2, -1.556989798598866e2, 6.680131188771972e1, -1.328068155288572e1];
  const c = [-7.784894002430293e-3, -3.223964580411365e-1, -2.400758277161838, -2.549732539343734, 4.374664141464968, 2.938163982698783];
  const d = [7.784695709041462e-3, 3.224671290700398e-1, 2.445134137142996, 3.754408661907416];
  const pl = 0.02425, ph = 1 - pl;
  let q, r;
  if (p < pl) { q = Math.sqrt(-2 * Math.log(p)); return (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1); }
  if (p > ph) { q = Math.sqrt(-2 * Math.log(1 - p)); return -(((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) / ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1); }
  q = p - 0.5; r = q * q;
  return (((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) * q / (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1);
}
const gapQ = [];
for (let i = 0; i < 256; i++) gapQ.push(Math.round(1000 * Math.exp(0.45 * invNorm((i + 0.5) / 256))));
writeFileSync(join(out, 'gapQuantile.ts'), header('log-normal(σ=0.45) multiplier quantiles, per-mille, 256 entries') +
  `export const GAP_QUANTILE_PM: readonly number[] = ${JSON.stringify(gapQ)};\n`);

// 3) Exponential decays indexed by calendar gap 0..400.
const N = 400;
const joyPull = [], luckKeep = [], debtGrow = [];
for (let g = 0; g <= N; g++) {
  joyPull.push(Math.round(1000 * (1 - Math.pow(0.7, g / 365))));
  luckKeep.push(Math.round(10000 * Math.pow(0.85, g / 365)));
  debtGrow.push(Math.round(1_000_000 * Math.pow(1.18, g / 365)));
}
writeFileSync(join(out, 'decay.ts'), header('exponential decays by calendar gap (index 0..400)') +
  `export const DECAY_MAX_GAP = ${N};\n` +
  `/** 1 − 0.70^(g/365), per-mille (02 §2.2.2 joy pull). */\nexport const JOY_PULL_PM: readonly number[] = ${JSON.stringify(joyPull)};\n` +
  `/** 0.85^(g/365), basis points (02 §2.2.5 luck reversion). */\nexport const LUCK_KEEP_BP: readonly number[] = ${JSON.stringify(luckKeep)};\n` +
  `/** 1.18^(g/365), ppm (02 §2.3.4 card-debt growth). */\nexport const DEBT_GROW_PPM: readonly number[] = ${JSON.stringify(debtGrow)};\n`);

// 4) tanh on [0, 4] in 64 steps (65 entries), per-mille; linear interpolation in the engine.
const tanhT = [];
for (let i = 0; i <= 64; i++) tanhT.push(Math.round(1000 * Math.tanh(i / 16)));
writeFileSync(join(out, 'tanh.ts'), header('tanh(x) for x = i/16, i = 0..64, per-mille') +
  `export const TANH_STEP_INV = 16;\nexport const TANH_PM: readonly number[] = ${JSON.stringify(tanhT)};\n`);

console.log('tables written to', out);
